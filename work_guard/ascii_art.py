def get_entry(level: int = 0) -> tuple[str, str]:
    """Returns (art, message) for the given urgency level (0, 1, 2)."""
    entry = random.choice(ENTRIES)
    level = min(level, len(entry["messages"]) - 1)
    return entry["art"], entry["messages"][level]


def get_random_art() -> str:
    return random.choice(ENTRIES)["art"]
